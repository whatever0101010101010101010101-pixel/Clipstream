export const integrationStatus = (platform) => {
  const configured = (platform.apiEnv || []).every((key) => Boolean(process.env[key]));
  return {
    platform: platform.id,
    configured,
    mode: configured ? 'api' : 'manual',
    apiScope: platform.apiScope,
    requiredEnv: platform.apiEnv,
    note: configured
      ? 'API credentials detected in the environment. Sync will use the official public API.'
      : 'Official API credentials are not configured on this deployment. Connect the account in manual mode and upload videos for full analysis, or add the listed environment variables.',
  };
};

